"""Undo on modern default schemas. Supabase and Django (4.1+) create `id` as an
IDENTITY column, and generated (computed) columns are common. Undo must restore
these tables exactly, not refuse them."""
import os
from urllib.parse import urlparse, urlunparse

import psycopg
import pytest
from testcontainers.community.postgres import PostgresContainer

from lomberk.capture.install import install_lomberk
from lomberk.executor import LomberkExecutor
from lomberk.models import ClassifiedStatement, PolicyDecision, StatementClass, StatementEvaluation

TABLES = ("accounts", "ledger")


@pytest.fixture(scope="module")
def db():
    with PostgresContainer(os.environ.get("LOMBERK_TEST_PG_IMAGE", "postgres:16-alpine")) as pg:
        dsn = pg.get_connection_url().replace("postgresql+psycopg2://", "postgresql://")
        p = urlparse(dsn)

        def as_role(role):
            return urlunparse((p.scheme, f"{role}:secret@{p.hostname}:{p.port}", p.path, "", "", ""))

        with psycopg.connect(dsn, autocommit=True) as conn, conn.cursor() as cur:
            cur.execute("CREATE ROLE lomberk_control LOGIN PASSWORD 'secret'")
            cur.execute("CREATE ROLE mcp_agent LOGIN PASSWORD 'secret'")
        install_lomberk(dsn, control_role="lomberk_control", agent_role="mcp_agent")
        with psycopg.connect(dsn, autocommit=True) as conn, conn.cursor() as cur:
            cur.execute("""
                -- Supabase dashboard / Django default
                CREATE TABLE public.accounts (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    email TEXT NOT NULL,
                    email_lower TEXT GENERATED ALWAYS AS (lower(email)) STORED
                );
                -- strict identity: explicit values need OVERRIDING SYSTEM VALUE
                CREATE TABLE public.ledger (
                    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                    account_id BIGINT REFERENCES public.accounts(id) ON DELETE CASCADE,
                    cents INT NOT NULL,
                    dollars NUMERIC GENERATED ALWAYS AS (cents / 100.0) STORED
                );
                INSERT INTO public.accounts (email) VALUES ('Alice@X.com'), ('Bob@X.com');
                INSERT INTO public.ledger (account_id, cents) VALUES (1, 500), (1, 700), (2, 50);
            """)
            for t in TABLES:
                cur.execute("SELECT lomberk.register_table('public', %s, 'id', 'mcp_agent')", (t,))
        yield dsn, LomberkExecutor(as_role("lomberk_control"), as_role("mcp_agent"))


@pytest.fixture(autouse=True)
def no_llm(monkeypatch):
    monkeypatch.setattr("lomberk.sentinel.AISentinel.evaluate_intent", lambda self, sql, tables: (True, ""))


def run(ex, sql):
    stmt = ClassifiedStatement(sql=sql, stmt_class=StatementClass.WRITE_DML, tables=[])
    return ex.execute(StatementEvaluation(statement=stmt, decision=PolicyDecision.ALLOW_WITH_CAPTURE, reason=""))


def snapshot(dsn):
    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        out = {}
        for t in TABLES:
            cur.execute(f"SELECT * FROM public.{t} ORDER BY id")
            out[t] = cur.fetchall()
        return out


@pytest.mark.parametrize("sql", [
    "DELETE FROM public.accounts WHERE id = 1",                     # identity + cascade into ALWAYS identity
    "UPDATE public.accounts SET email = 'Mallory@X.com' WHERE id = 2",  # generated column recomputes
    "UPDATE public.ledger SET cents = 0 WHERE id > 0",
    "INSERT INTO public.ledger (account_id, cents) VALUES (2, 999)",
])
def test_undo_restores_identity_and_generated_tables(db, sql):
    dsn, ex = db
    before = snapshot(dsn)
    res = run(ex, sql)
    assert res.status == "applied", res.message
    assert snapshot(dsn) != before

    undo = ex.execute_undo(res.public_id)
    assert undo.status == "undone", undo.message
    assert snapshot(dsn) == before


def test_new_rows_after_undo_do_not_collide(db):
    # Re-inserted ids came from the sequence already, so later inserts must still work.
    _dsn, ex = db
    res = run(ex, "INSERT INTO public.accounts (email) VALUES ('new@x.com')")
    assert res.status == "applied", res.message
